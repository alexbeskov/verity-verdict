export function buildUserPrompt(documents: { name: string; content: string }[]): string {
  let text = 'ПАКЕТ ДОКУМЕНТОВ КОМПАНИИ:\n\n';
  for (const doc of documents) {
    text += `=== ДОКУМЕНТ: ${doc.name} ===\n${doc.content}\n\n`;
  }
  text += 'Проведи due diligence анализ и верни результат СТРОГО в формате JSON, без пояснений вне JSON.';
  return text;
}
